class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem('pureharvest_lang') || 'en';
    document.addEventListener('DOMContentLoaded', () => {
      this.init();
    });
  }

  init() {
    this.applyLanguage(this.currentLang);
    this.updateLanguageButton();
  }

  getLanguage() {
    return this.currentLang;
  }

  toggleLanguage() {
    const nextLang = this.currentLang === 'en' ? 'bn' : 'en';
    this.setLanguage(nextLang);
  }

  setLanguage(lang) {
    if (!TRANSLATIONS[lang]) return;
    this.currentLang = lang;
    localStorage.setItem('pureharvest_lang', lang);
    this.applyLanguage(lang);
    this.updateLanguageButton();

    // Re-render other components if active
    if (window.catalogManager && typeof window.catalogManager.render === 'function') {
      window.catalogManager.render();
    }
    if (window.boxBuilderManager && typeof window.boxBuilderManager.render === 'function') {
      window.boxBuilderManager.render();
    }
    if (window.cartManager && typeof window.cartManager.render === 'function') {
      window.cartManager.render();
    }
    if (window.app && typeof window.app.initTestimonials === 'function') {
      window.app.initTestimonials();
    }

    const toastMsg = lang === 'bn' 
      ? "ভাষা সফলভাবে বাংলায় পরিবর্তন করা হয়েছে! 🇧🇩" 
      : "Language switched to English successfully! 🇺🇸";
    
    if (window.app && typeof window.app.showToast === 'function') {
      window.app.showToast(toastMsg, 'success');
    }
  }

  applyLanguage(lang) {
    document.documentElement.lang = lang;
    if (lang === 'bn') {
      document.body.classList.add('lang-bn');
    } else {
      document.body.classList.remove('lang-bn');
    }

    // Replace all elements with [data-i18n]
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) {
        el.innerHTML = TRANSLATIONS[lang][key];
      }
    });

    // Replace placeholder texts with [data-i18n-placeholder]
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) {
        el.placeholder = TRANSLATIONS[lang][key];
      }
    });

    // Replace title attributes with [data-i18n-title]
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      if (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) {
        el.title = TRANSLATIONS[lang][key];
      }
    });
  }

  updateLanguageButton() {
    const label = document.getElementById('langSwitchLabel');
    if (label) {
      label.textContent = this.currentLang === 'en' ? 'বাংলা' : 'English';
    }
  }

  t(key, fallback = '') {
    if (TRANSLATIONS[this.currentLang] && TRANSLATIONS[this.currentLang][key]) {
      return TRANSLATIONS[this.currentLang][key];
    }
    if (TRANSLATIONS.en && TRANSLATIONS.en[key]) {
      return TRANSLATIONS.en[key];
    }
    return fallback;
  }

  // Product helper helpers for dynamic catalog, quickview, cart, checkout
  getProductName(product) {
    if (this.currentLang === 'bn' && PRODUCTS_BN[product.id]) {
      return PRODUCTS_BN[product.id].name;
    }
    return product.name;
  }

  getProductUnit(product) {
    if (this.currentLang === 'bn' && PRODUCTS_BN[product.id]) {
      return PRODUCTS_BN[product.id].unit;
    }
    return product.unit;
  }

  getProductDesc(product) {
    if (this.currentLang === 'bn' && PRODUCTS_BN[product.id]) {
      return PRODUCTS_BN[product.id].description;
    }
    return product.description;
  }

  getProductTastes(product) {
    if (this.currentLang === 'bn' && PRODUCTS_BN[product.id] && PRODUCTS_BN[product.id].tastes) {
      return PRODUCTS_BN[product.id].tastes;
    }
    return product.tastes;
  }

  getProductBadge(product) {
    if (this.currentLang === 'bn' && PRODUCTS_BN[product.id] && PRODUCTS_BN[product.id].badge) {
      return PRODUCTS_BN[product.id].badge;
    }
    if (product.badge === 'organic') return this.t('badgeOrganic', 'USDA Organic');
    if (product.badge === 'seasonal') return this.t('badgeSeasonal', 'Peak Season');
    if (product.badge === 'rare') return this.t('badgeRare', 'Heirloom Rare');
    return product.badge;
  }

  getProductFarm(product) {
    if (this.currentLang === 'bn' && PRODUCTS_BN[product.id] && PRODUCTS_BN[product.id].farm) {
      return {
        ...product.farm,
        ...PRODUCTS_BN[product.id].farm
      };
    }
    return product.farm;
  }

  getTestimonials() {
    if (this.currentLang === 'bn') {
      return TESTIMONIALS_DATA.map((t, idx) => {
        const bn = TESTIMONIALS_BN[idx] || {};
        return {
          ...t,
          name: bn.name || t.name,
          role: bn.role || t.role,
          comment: bn.comment || t.comment,
          location: bn.location || t.location
        };
      });
    }
    return TESTIMONIALS_DATA;
  }
}

// Instantiate globally
window.i18n = new I18nManager();
